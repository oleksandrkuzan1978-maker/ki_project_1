# Модуль для доступа к переменным окружения, где можно хранить ключ API.
import os

# Библиотека для обращения к моделям Google; genai — её короткое имя.
import google.generativeai as genai
# Функция для загрузки настроек из файла .env.
from dotenv import load_dotenv

# Загружаем значения из .env в переменные окружения.
load_dotenv()

# Получаем ключ доступа; если переменной нет, результатом будет None.
api_key = os.getenv("GEMINI_API_KEY")
# Печатаем первые пять символов ключа для проверки загрузки; при None здесь будет ошибка.
print(api_key[:5])

# Передаём ключ библиотеке для авторизации запросов к API.
genai.configure(api_key=api_key)

# Отключённый пример выбора другой модели: строка с # не выполняется.
#model = genai.GenerativeModel("gemini-2.5-flash")
# Создаём объект с указанным именем модели; для запроса модель должна быть доступна в API.
model = genai.GenerativeModel("gemini-3.8-flash")

# Отключённый пример другого вопроса к модели.
#response = model.generate_content("почему при одинаковой архитектуре llm и одинаковом промпте всегда генерируются разные токены и разный ответ?")
# Отправляем вопрос модели и ждём ответ; текущая дата в запрос автоматически не подставляется.
response = model.generate_content("какой сегодня день недели, месяц, год?")
# Выводим текстовую часть ответа модели.
print(response.text)


