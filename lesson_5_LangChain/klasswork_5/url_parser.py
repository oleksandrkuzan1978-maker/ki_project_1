# 1. Подключаем инструменты, необходимые для загрузки страницы и её краткого изложения.
# Эта функция собирает цепочку: объединяет тексты документов, подставляет их
# в запрос и передаёт запрос языковой модели.
from langchain.chains.combine_documents import create_stuff_documents_chain

# Шаблон позволяет подготовить запрос с местом для текста страницы.
from langchain_core.prompts import ChatPromptTemplate

# Подключаем клиент для обращения к модели Gemini через сервис Google.
from langchain_google_genai import ChatGoogleGenerativeAI

# Загрузчик получает содержимое веб-страницы и извлекает из него текст.
from langchain_community.document_loaders import WebBaseLoader

# load_dotenv загружает настройки из файла .env в переменные окружения.
from dotenv import load_dotenv

# Модуль os позволяет читать переменные окружения, в том числе ключ API.
import os


# 2. Загружаем настройки и получаем ключ для доступа к Gemini.
# Сам ключ хранится вне кода: например, в .env в записи GEMINI_API_KEY=значение.
load_dotenv()
# Если переменная не задана, getenv вернёт None. Отдельной проверки здесь нет.
api_key = os.getenv("GEMINI_API_KEY")


# 3. Создаём объект для работы с моделью gemini-2.5-flash.
# При запуске цепочки запрос и текст страницы будут отправлены в сервис Google;
# модель не загружается на этот компьютер.
llm = ChatGoogleGenerativeAI(model="gemini-2.5-flash", google_api_key=api_key)


# 4. Описываем функцию, которая загружает текст по переданному адресу страницы.
def get_docs(url):
    # Создаём загрузчик для указанного URL.
    loader = WebBaseLoader(url)
    # Загружаем страницу и получаем список документов LangChain.
    # В каждом документе извлечённый текст хранится в поле page_content.
    docs = loader.load()
    # Возвращаем документы, чтобы затем передать их в цепочку.
    return docs


# 5. Создаём шаблон инструкции для модели.
# Вместо {context} цепочка подставит текст загруженных документов.
prompt = ChatPromptTemplate.from_template("Напишите краткое изложение следующего текста: {context}")


# 6. Соединяем модель и шаблон в одну цепочку обработки.
# Она объединяет документы в один запрос; разбиения длинной страницы
# на части в этом коде нет, поэтому запрос должен помещаться в лимит модели.
chain = create_stuff_documents_chain(llm, prompt)


# 7. Запрашиваем адрес страницы у пользователя через консоль.
user_url = input('Введите адрес веб-страницы для парсинга: ')
# Сначала get_docs загружает страницу, затем invoke запускает цепочку.
# Ключ context передаёт документы для подстановки их текста в шаблон запроса.
# Полученное от Gemini краткое изложение сохраняется в переменной result.
result = chain.invoke({"context": get_docs(user_url)})


# 8. Показываем готовое краткое изложение в консоли.
print(result)
